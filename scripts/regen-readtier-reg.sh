emit() { # name | in | out | effect | deterministic | idempotent
  local name="$1" ins="$2" out="$3" eff="$4" det="$5" idem="$6"
  local id
  id=$(printf '%s' "$name" | sha256sum | cut -d' ' -f1)
  cat <<EOF

fn $name
  identity 0x$id
  kind leaf
  in ($ins)
  out $out
  effect $eff
  deterministic $det
  idempotent $idem
end
EOF
}

