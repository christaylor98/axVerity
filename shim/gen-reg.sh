#!/usr/bin/env bash
# Regenerate shim/registries/axverity-shim.axreg from lib/*.m1 signatures.
# identity = sha256(utf8(name)), nothing else (CLAUDE.md §3).
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=$HERE/registries/axverity-shim.axreg

declare -A SIG=(
  [sh_vi_width]="(Bytes, Int)|Int|pure|true|true"
  [sh_vi_val]="(Bytes, Int, Int)|Int|pure|true|true"
  [sh_vi_enc]="(Int)|Bytes|fullIo|false|false"
  [sh_recv_more]="(Int)|Bool|fullIo|false|false"
  [sh_recv_step]="(Int)|Int|fullIo|false|false"
  [sh_recv_frame]="(Int, Int)|Int|fullIo|false|false"
  [sh_send]="(Int, Bytes)|Unit|fullIo|false|false"
  [sh_rb_append]="(Bytes)|Unit|fullIo|false|false"
  [sh_dispatch]="(Int, Int, Int)|Int|fullIo|false|false"
  [sh_index_step]="(Int)|Int|fullIo|false|false"
  [sh_acceptor]="(Value)|Value|fullIo|false|false"
  [sh_spawn_acceptors]="(Int)|Int|fullIo|false|false"
  [sh_spawn_more]="(Text)|Bool|fullIo|false|false"
  [sh_spawn_step]="(Text)|Text|fullIo|false|false"
  [sh_always]="(Int)|Bool|fullIo|false|false"
  [sh_reply]="(Int, Int, Text)|Unit|fullIo|false|false"
  [sh_query]="(Int, Text)|Int|fullIo|false|false"
  [sh_query_step]="(Int)|Int|fullIo|false|false"
  [sh_admit]="(Int, Int, Int)|Int|fullIo|false|false"
  [sh_frames]="(Int, Int, Int)|Int|fullIo|false|false"
  [sh_fr_more]="(Int)|Bool|fullIo|false|false"
  [sh_fr_step]="(Int)|Int|fullIo|false|false"
  [sh_serve_more]="(Int)|Bool|fullIo|false|false"
  [sh_serve_step]="(Int)|Int|fullIo|false|false"
  [sh_serve_conn]="(Int, Int)|Int|fullIo|false|false"
  [sh_accept_more]="(Int)|Bool|fullIo|false|false"
  [sh_accept_step]="(Int)|Int|fullIo|false|false"
  [sh_byte_at]="(Int, Int)|Int|fullIo|false|false"
  [sh_rebuild]="(Int)|Int|fullIo|false|false"
  [sh_name3]="(Text)|Text|fullIo|false|false"
  [sh_seps2]="(Int, Int, Int)|Bool|fullIo|false|false"
)

{
cat <<'HDR'
// axverity-shim.axreg — AXVERITY_SHIM_BUILD_V1.
//
// A registry of its own, under shim/, because the shim is a CONSUMER of
// axVerity and not a part of it. Nothing in registries/ was touched: the
// shim's build co-feeds registries/axverity-readtier.axreg read-only, exactly
// as any other consumer linking the tiers in-process would.
//
// Every fn is kind leaf; bodies resolve via --lib-dir shim/lib_coreir at link
// time. identity = sha256(utf8(name)), nothing else. Types are declared in
// axis-bridge.axreg and co-fed with every invocation — not redeclared here.
//
// The outer shim/src/shim.m1 gets no entry: --entries binaries resolve by file
// stem at bridge link time, not by registry identity.
//
// Generated by shim/gen-reg.sh — edit that, not this.

registry axverity-shim 0.1
HDR
for name in $(printf '%s\n' "${!SIG[@]}" | sort); do
  IFS='|' read -r in out eff det idem <<< "${SIG[$name]}"
  id=$(printf '%s' "$name" | sha256sum | cut -d' ' -f1)
  printf '\nfn %s\n  identity 0x%s\n  kind leaf\n  in %s\n  out %s\n  effect %s\n  deterministic %s\n  idempotent %s\nend\n' \
    "$name" "$id" "$in" "$out" "$eff" "$det" "$idem"
done
} > "$OUT"
echo "wrote $OUT ($(grep -c '^fn ' "$OUT") fns)"
